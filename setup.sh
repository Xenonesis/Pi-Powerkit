#!/usr/bin/env bash
set -e

PI_DIR="$HOME/.pi/agent"
SRC_DIR="$(cd "$(dirname "$0")" && pwd)"
INTERACTIVE=true
[[ "$1" == "--no-interactive" ]] && INTERACTIVE=false

echo "================================================"
echo "   Pi-Powerkit - One-Click Setup"
echo "   Configures Pi + OMP + Zed + Copilot + jcode"
echo "================================================"
echo ""

mkdir -p "$PI_DIR"/extensions "$PI_DIR"/cache

# Source .env
ENV_FILE="$SRC_DIR/.env"
[ -f "$ENV_FILE" ] && set -a && source "$ENV_FILE" && set +a && echo "  -> .env loaded"

# Prompt for API keys
echo ""
for var in AIHUBMIX_API_KEY ROUTER9_API_KEY XIAOMI_API_KEY DATABRICKS_API_KEY MODAL_API_KEY KILO_API_KEY AGENTROUTER_API_KEY; do
  VAL="${!var}"
  if [ -z "$VAL" ] && [ "$INTERACTIVE" = true ]; then
    read -rp "  Enter $var (or press Enter to skip): " VAL
    export "$var=$VAL"
  fi
done

# =========================================================
#  1. PI SETUP
# =========================================================
echo ""
echo "--- Pi ---"

# settings.json
if [ ! -f "$PI_DIR/settings.json" ]; then
  if [ -f "$SRC_DIR/bootstrap/settings.json" ]; then
    cp "$SRC_DIR/bootstrap/settings.json" "$PI_DIR/settings.json"
    echo "  settings.json created"
  fi
else
  echo "  settings.json exists (skipped)"
fi

# models.json
echo "  Generating models.json..."
TEMPLATE=$(cat "$SRC_DIR/bootstrap/models.json")
for var in AIHUBMIX_API_KEY ROUTER9_API_KEY XIAOMI_API_KEY DATABRICKS_API_KEY MODAL_API_KEY KILO_API_KEY AGENTROUTER_API_KEY; do
  VAL="${!var}"
  [ -z "$VAL" ] && VAL="YOUR_${var}"
  ESCAPED_VAL=$(printf '%s\n' "$VAL" | sed 's/[&/\]/\\&/g')
  TEMPLATE=$(echo "$TEMPLATE" | sed "s/\${$var}/$ESCAPED_VAL/g")
done
echo "$TEMPLATE" > "$PI_DIR/models.json"
echo "  models.json generated"

# Extensions
echo "  Copying extensions..."
for ext in pi-ddg-search pi-ssh; do
  SRC="$SRC_DIR/packages/$ext/extensions"
  [ -d "$SRC" ] && cp "$SRC"/*.ts "$PI_DIR/extensions/" 2>/dev/null && echo "  -> $ext copied"
done

# .env.example
if [ ! -f "$PI_DIR/.env" ] && [ -f "$SRC_DIR/bootstrap/.env.example" ]; then
  cp "$SRC_DIR/bootstrap/.env.example" "$PI_DIR/.env"
  echo "  .env example copied"
fi

# =========================================================
#  2. OMP SETUP (~/.omp/agent/models.yml)
# =========================================================
echo ""
echo "--- OMP (Oh My Pi) ---"
OMP_DIR="$HOME/.omp/agent"
if [ -d "$OMP_DIR" ]; then
  OMP_FILE="$OMP_DIR/models.yml"
  echo "# Custom providers (generated by Pi-Powerkit setup)" > "$OMP_FILE"
  echo "providers:" >> "$OMP_FILE"
  for name in router9 databricks agentrouter aihubmix; do
    KEY_VAR=$(echo "${name}_API_KEY" | tr '[:lower:]' '[:upper:]')
    KEY_VAL="${!KEY_VAR}"
    [ -z "$KEY_VAL" ] && KEY_VAL="YOUR_${KEY_VAR}"
    case "$name" in
      router9)
        echo "  router9:" >> "$OMP_FILE"
        echo "    baseUrl: https://api.router9.com/v1" >> "$OMP_FILE"
        echo "    apiKey: $KEY_VAL" >> "$OMP_FILE"
        echo "    auth: apiKey" >> "$OMP_FILE"
        echo "    api: openai-completions" >> "$OMP_FILE"
        echo "    models:" >> "$OMP_FILE"
        echo "      - id: minimax/minimax-m3" >> "$OMP_FILE"
        echo "        name: MiniMax M3 (via Router9)" >> "$OMP_FILE"
        echo "        reasoning: true" >> "$OMP_FILE"
        echo "        input: [text, image]" >> "$OMP_FILE"
        echo "        contextWindow: 1000000" >> "$OMP_FILE"
        echo "        maxTokens: 65536" >> "$OMP_FILE"
        ;;
      databricks)
        echo "  databricks:" >> "$OMP_FILE"
        echo "    baseUrl: https://dbc-3e029138-076b.cloud.databricks.com/ai-gateway/mlflow/v1" >> "$OMP_FILE"
        echo "    apiKey: $KEY_VAL" >> "$OMP_FILE"
        echo "    auth: apiKey" >> "$OMP_FILE"
        echo "    api: openai-completions" >> "$OMP_FILE"
        echo "    models:" >> "$OMP_FILE"
        echo "      - id: system.ai.glm-5-2" >> "$OMP_FILE"
        echo "        name: Databricks GLM-5-2" >> "$OMP_FILE"
        echo "        reasoning: false" >> "$OMP_FILE"
        echo "        input: [text]" >> "$OMP_FILE"
        echo "        contextWindow: 128000" >> "$OMP_FILE"
        echo "        maxTokens: 32768" >> "$OMP_FILE"
        ;;
      agentrouter)
        echo "  agentrouter:" >> "$OMP_FILE"
        echo "    baseUrl: https://agentrouter.org/v1" >> "$OMP_FILE"
        echo "    apiKey: $KEY_VAL" >> "$OMP_FILE"
        echo "    auth: apiKey" >> "$OMP_FILE"
        echo "    api: openai-completions" >> "$OMP_FILE"
        echo "    models:" >> "$OMP_FILE"
        echo "      - id: claude-opus-4-8" >> "$OMP_FILE"
        echo "        name: Claude Opus 4.8 (via AgentRouter)" >> "$OMP_FILE"
        echo "        reasoning: true" >> "$OMP_FILE"
        echo "        input: [text]" >> "$OMP_FILE"
        echo "        contextWindow: 1000000" >> "$OMP_FILE"
        echo "        maxTokens: 128000" >> "$OMP_FILE"
        ;;
      aihubmix)
        echo "  aihubmix:" >> "$OMP_FILE"
        echo "    baseUrl: https://aihubmix.com/v1" >> "$OMP_FILE"
        echo "    apiKey: $KEY_VAL" >> "$OMP_FILE"
        echo "    auth: apiKey" >> "$OMP_FILE"
        echo "    api: openai-completions" >> "$OMP_FILE"
        echo "    models:" >> "$OMP_FILE"
        echo "      - id: coding-glm-5.2-free" >> "$OMP_FILE"
        echo "        name: Coding GLM-5.2 Free" >> "$OMP_FILE"
        echo "        reasoning: true" >> "$OMP_FILE"
        echo "        input: [text]" >> "$OMP_FILE"
        echo "        contextWindow: 128000" >> "$OMP_FILE"
        echo "        maxTokens: 65536" >> "$OMP_FILE"
        ;;
    esac
    echo "" >> "$OMP_FILE"
  done
  echo "  models.yml generated ($OMP_FILE)"
else
  echo "  OMP not installed (no ~/.omp/agent dir) — skipped"
fi

# =========================================================
#  3. ZED SETUP (~/.config/zed/settings.json)
# =========================================================
echo ""
echo "--- Zed ---"
ZED_FILE="$HOME/.config/zed/settings.json"
if [ -f "$ZED_FILE" ]; then
  python3 << 'PYEOF' "$ZED_FILE"
