    d.append({
        "name": "AIHubMix FREE",
        "vendor": "customendpoint",
        "apiKey": "",
        "apiType": "chat-completions",
        "models": [
            {"id": "coding-glm-5.2-free", "name": "Coding GLM-5.2 (FREE)", "url": "https://aihubmix.com/v1/chat/completions", "toolCalling": True, "thinking": True, "supportsReasoningEffort": ["low","medium","high"], "maxInputTokens": 128000, "maxOutputTokens": 65536},
            {"id": "coding-kimi-k3-free", "name": "Coding Kimi K3 (FREE)", "url": "https://aihubmix.com/v1/chat/completions", "toolCalling": True, "maxInputTokens": 128000, "maxOutputTokens": 32768},
            {"id": "gemini-3.6-flash-free", "name": "Gemini 3.6 Flash (FREE)", "url": "https://aihubmix.com/v1/chat/completions", "toolCalling": True, "maxInputTokens": 128000, "maxOutputTokens": 32768},
            {"id": "gemma-4-26b-a4b-it-free", "name": "Gemma 4 26B (FREE)", "url": "https://aihubmix.com/v1/chat/completions", "toolCalling": True, "maxInputTokens": 262144, "maxOutputTokens": 32768},
            {"id": "gpt-5.5-free", "name": "GPT-5.5 (FREE)", "url": "https://aihubmix.com/v1/chat/completions", "toolCalling": True, "maxInputTokens": 272000, "maxOutputTokens": 65536},
            {"id": "kimi-for-coding-free", "name": "Kimi for Coding (FREE)", "url": "https://aihubmix.com/v1/chat/completions", "toolCalling": True, "maxInputTokens": 128000, "maxOutputTokens": 16384}
        ]
    })
    print("  AIHubMix FREE added to Copilot")
else:
    print("  AIHubMix already in Copilot (skipped)")

with open(f, 'w') as fp:
    json.dump(d, fp, indent=2)
    fp.write('\n')
PYEOF
else
  echo "  VS Code Copilot not installed (no chatLanguageModels.json) — skipped"
fi

# =========================================================
#  5. JCODE SETUP (jcode provider add)
# =========================================================
echo ""
echo "--- jcode ---"
if command -v jcode &>/dev/null; then
  AIHUBMIX_KEY="${AIHUBMIX_API_KEY:-}"
  if [ -n "$AIHUBMIX_KEY" ] && ! jcode provider list 2>/dev/null | grep -q aihubmix; then
    echo "$AIHUBMIX_KEY" | jcode provider add aihubmix \
      --base-url https://aihubmix.com/v1 \
      --model coding-glm-5.2-free \
      --api-key-stdin \
      --context-window 128000 \
      --no-update 2>/dev/null && echo "  aihubmix provider added to jcode" || echo "  jcode aihubmix skipped"
  else
    echo "  aihubmix already in jcode or no key (skipped)"
  fi
else
  echo "  jcode not installed — skipped"
fi

# =========================================================
#  6. INSTALL AGENT-BROWSER
# =========================================================
echo ""
echo "--- Browser ---"
if ! command -v agent-browser &>/dev/null; then
  echo "  Installing agent-browser..."
  npm install -g agent-browser 2>/dev/null || npm install agent-browser --prefix "$HOME/.local" 2>/dev/null || true
  echo "  agent-browser installed"
else
  echo "  agent-browser already installed"
fi

# =========================================================
#  DONE
# =========================================================
echo ""
echo "================================================"
echo "   Setup complete!"
echo "================================================"
echo ""
echo "  Configured:"
echo "    - Pi: 8 providers, 50+ models + search + SSH"
echo "    - OMP: custom providers (if installed)"
echo "    - Zed: aihubmix + router9 (if installed)"
echo "    - Copilot: AIHubMix FREE (if VS Code installed)"
echo "    - jcode: aihubmix provider (if jcode installed)"
echo ""
echo "  Next:"
echo "    1. Edit .env for missing API keys"
echo "    2. Restart pi (and other tools)"
echo ""
