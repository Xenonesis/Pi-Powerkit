    {"name": "coding-glm-5.2-free", "display_name": "Coding GLM-5.2 (FREE)", "max_tokens": 128000, "max_output_tokens": 65536, "protocol": "openai_chat", "subscription": "free", "reasoning_effort_levels": ["low","medium","high"], "interleaved_reasoning": True},
