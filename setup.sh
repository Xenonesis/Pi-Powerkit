oc.setdefault('router9', {'api_url': 'https://api.router9.com/v1', 'available_models': [
    {"name": "minimax/minimax-m3", "display_name": "MiniMax M3 (Router9)", "max_tokens": 1000000, "max_output_tokens": 65536}
]})

with open(f, 'w') as fp:
    json.dump(d, fp, indent=2)
    fp.write('\n')

print("  aihubmix + router9 added to settings.json")
PYEOF
else
  echo "  Zed not installed (no settings.json) — skipped"
fi

# =========================================================
#  4. COPILOT SETUP (~/.config/Code/User/chatLanguageModels.json)
# =========================================================
echo ""
echo "--- VS Code Copilot ---"
COPILOT_FILE="$HOME/.config/Code/User/chatLanguageModels.json"
if [ -f "$COPILOT_FILE" ]; then
  python3 << 'PYEOF' "$COPILOT_FILE"
