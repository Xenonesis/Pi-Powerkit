    {"name": "gemma-4-26b-a4b-it-free", "display_name": "Gemma 4 26B (FREE)", "max_tokens": 262144, "max_output_tokens": 32768, "protocol": "openai_chat", "subscription": "free"},
    {"name": "gpt-5.5-free", "display_name": "GPT-5.5 (FREE)", "max_tokens": 272000, "max_output_tokens": 65536, "protocol": "openai_chat", "subscription": "free"},
    {"name": "nemotron-3-nano-30b-a3b-free", "display_name": "Nemotron 3 Nano 30B (FREE)", "max_tokens": 128000, "max_output_tokens": 16384, "protocol": "openai_chat", "subscription": "free"},
    {"name": "xiaomi-mimo-v2.5-free", "display_name": "MiMo V2.5 (FREE)", "max_tokens": 1048576, "max_output_tokens": 131072, "protocol": "openai_chat", "subscription": "free"},
    {"name": "kimi-for-coding-free", "display_name": "Kimi for Coding (FREE)", "max_tokens": 128000, "max_output_tokens": 16384, "protocol": "openai_chat", "subscription": "free"}
